-- WiseLife data architecture: incremental PostgreSQL/Supabase model.
-- This migration is intentionally not executed by v0; review and apply through the project's migration workflow.
-- All CREATE operations are guarded because the connected project already contains production tables.

create schema if not exists private;

-- Authorization source of truth. Never derive authorization from user-editable user_metadata.
create table if not exists public.app_roles (
  code text primary key,
  description text not null,
  created_at timestamptz not null default now(),
  constraint app_roles_code_ck check (code = lower(code) and code ~ '^[a-z][a-z0-9_]{1,63}$')
);

create table if not exists public.user_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role_code text not null references public.app_roles(code) on delete restrict,
  granted_at timestamptz not null default now(),
  granted_by uuid references auth.users(id) on delete set null,
  primary key (user_id, role_code)
);

insert into public.app_roles (code, description)
values ('admin', 'Administración de la plataforma'), ('psychologist', 'Profesional clínico'), ('patient', 'Paciente')
on conflict (code) do nothing;

-- Normalize profile referral arrays without removing the legacy column yet.
create table if not exists public.referral_sources (
  id bigint generated by default as identity primary key,
  code text not null unique,
  display_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint referral_sources_code_ck check (code = lower(code) and length(trim(code)) > 0)
);

create table if not exists public.profile_referral_sources (
  profile_id uuid not null references public.profiles(id) on delete cascade,
  referral_source_id bigint not null references public.referral_sources(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (profile_id, referral_source_id)
);

-- Normalize psychologist specialties while retaining psychologists.specialties for compatibility.
create table if not exists public.specialties (
  id bigint generated by default as identity primary key,
  code text not null unique,
  display_name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint specialties_code_ck check (code = lower(code) and length(trim(code)) > 0)
);

create table if not exists public.psychologist_specialties (
  psychologist_id uuid not null references public.psychologists(id) on delete cascade,
  specialty_id bigint not null references public.specialties(id) on delete restrict,
  created_at timestamptz not null default now(),
  primary key (psychologist_id, specialty_id)
);

-- Structured clinical diagnoses; legacy diagnosis fields remain available during migration.
create table if not exists public.session_note_diagnoses (
  session_note_id uuid not null references public.session_notes(id) on delete cascade,
  cie10_code varchar not null references public.cie10_codes(code) on delete restrict,
  diagnosis_order smallint not null default 1,
  is_primary boolean not null default false,
  clinical_description text,
  created_at timestamptz not null default now(),
  primary key (session_note_id, cie10_code),
  constraint session_note_diagnoses_order_ck check (diagnosis_order > 0)
);

create unique index if not exists session_note_one_primary_diagnosis_idx
  on public.session_note_diagnoses (session_note_id)
  where is_primary;

-- Append-only consent history. Current boolean columns remain legacy compatibility fields.
create table if not exists public.consent_events (
  id uuid primary key default gen_random_uuid(),
  patient_id uuid not null references public.profiles(id) on delete restrict,
  clinical_record_id uuid references public.clinical_records(id) on delete restrict,
  consent_type text not null,
  version text not null,
  accepted boolean not null,
  accepted_at timestamptz not null default now(),
  source text not null default 'web',
  actor_id uuid references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  constraint consent_events_type_ck check (consent_type in ('informed_consent', 'data_treatment')),
  constraint consent_events_source_ck check (source in ('web', 'admin', 'import', 'api'))
);

-- Immutable audit trail for access/change events on clinical data.
create table if not exists private.clinical_audit_events (
  id bigint generated always as identity primary key,
  occurred_at timestamptz not null default now(),
  actor_id uuid references auth.users(id) on delete set null,
  patient_id uuid references public.profiles(id) on delete set null,
  resource_table text not null,
  resource_id uuid,
  action text not null,
  request_id uuid,
  metadata jsonb not null default '{}'::jsonb,
  constraint clinical_audit_action_ck check (action in ('select', 'insert', 'update', 'delete', 'export'))
);

-- Immutable credit ledger; profiles.referral_credits remains a compatibility/cache column.
create table if not exists public.referral_credit_ledger (
  id bigint generated always as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete restrict,
  referral_id uuid references public.referrals(id) on delete restrict,
  delta integer not null,
  reason text not null,
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  constraint referral_credit_ledger_delta_ck check (delta <> 0),
  constraint referral_credit_ledger_reason_ck check (length(trim(reason)) > 0)
);

-- Conservative data-quality constraints are installed only when the target objects/columns exist.
do $$
begin
  if to_regclass('public.psychologist_availability') is not null then
    if not exists (select 1 from pg_constraint where conname = 'psychologist_availability_time_ck') then
      alter table public.psychologist_availability add constraint psychologist_availability_time_ck check (start_time < end_time) not valid;
    end if;
  end if;
  if to_regclass('public.schedule_blocks') is not null then
    if not exists (select 1 from pg_constraint where conname = 'schedule_blocks_time_ck') then
      alter table public.schedule_blocks add constraint schedule_blocks_time_ck check (start_time < end_time) not valid;
    end if;
  end if;
  if to_regclass('public.appointments') is not null then
    if not exists (select 1 from pg_constraint where conname = 'appointments_time_ck') then
      alter table public.appointments add constraint appointments_time_ck check (start_time < end_time) not valid;
    end if;
  end if;
end $$;

