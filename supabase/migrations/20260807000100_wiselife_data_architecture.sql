-- Helper remains in private schema and is not exposed through PostgREST.
create or replace function private.has_app_role(required_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.user_roles ur
    where ur.user_id = (select auth.uid()) and ur.role_code = required_role
  );
$$;

revoke all on function private.has_app_role(text) from public;
grant execute on function private.has_app_role(text) to authenticated;

create policy app_roles_select_authenticated on public.app_roles
  for select to authenticated using (true);
create policy user_roles_select_self_or_admin on public.user_roles
  for select to authenticated
  using (user_id = (select auth.uid()) or private.has_app_role('admin'));
create policy user_roles_admin_manage on public.user_roles
  for all to authenticated
  using (private.has_app_role('admin'))
  with check (private.has_app_role('admin'));
create policy referral_sources_select_authenticated on public.referral_sources
  for select to authenticated using (is_active or private.has_app_role('admin'));
create policy profile_referral_sources_self_read on public.profile_referral_sources
  for select to authenticated using (profile_id = (select auth.uid()));
create policy profile_referral_sources_self_write on public.profile_referral_sources
  for all to authenticated
  using (profile_id = (select auth.uid()))
  with check (profile_id = (select auth.uid()));
create policy specialties_select_authenticated on public.specialties
  for select to authenticated using (is_active or private.has_app_role('admin'));
create policy psychologist_specialties_select_authenticated on public.psychologist_specialties
  for select to authenticated using (true);
create policy psychologist_specialties_owner_write on public.psychologist_specialties
  for all to authenticated
  using (exists (select 1 from public.psychologists p where p.id = psychologist_id and p.user_id = (select auth.uid())))
  with check (exists (select 1 from public.psychologists p where p.id = psychologist_id and p.user_id = (select auth.uid())));
create policy session_note_diagnoses_clinical_read on public.session_note_diagnoses
  for select to authenticated
  using (exists (
    select 1 from public.session_notes sn
    where sn.id = session_note_id
      and (sn.patient_id = (select auth.uid()) or exists (
        select 1 from public.psychologists p where p.id = sn.psychologist_id and p.user_id = (select auth.uid())
      ))
  ));
create policy session_note_diagnoses_clinical_write on public.session_note_diagnoses
  for all to authenticated
  using (exists (
    select 1 from public.session_notes sn
    where sn.id = session_note_id
      and exists (select 1 from public.psychologists p where p.id = sn.psychologist_id and p.user_id = (select auth.uid()))
  ))
  with check (exists (
    select 1 from public.session_notes sn
    where sn.id = session_note_id
      and exists (select 1 from public.psychologists p where p.id = sn.psychologist_id and p.user_id = (select auth.uid()))
  ));
create policy consent_events_patient_or_clinician_read on public.consent_events
  for select to authenticated
  using (patient_id = (select auth.uid()) or private.has_app_role('admin') or exists (
    select 1 from public.clinical_records cr join public.psychologists p on p.id = cr.psychologist_id
    where cr.id = clinical_record_id and p.user_id = (select auth.uid())
  ));
create policy consent_events_patient_insert on public.consent_events
  for insert to authenticated
  with check (patient_id = (select auth.uid()) and actor_id = (select auth.uid()));
create policy referral_credit_ledger_self_read on public.referral_credit_ledger
  for select to authenticated using (profile_id = (select auth.uid()));
create policy clinical_audit_admin_read on private.clinical_audit_events
  for select to authenticated using (private.has_app_role('admin'));

